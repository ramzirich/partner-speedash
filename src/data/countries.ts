const BY_CODE: ReadonlyMap<string, Country> = new Map(
  COUNTRIES.map(country => [country.code, country]),
);

/** Never `undefined`: an unknown code falls back to the default country. */
export const getCountry = (code: string | undefined): Country =>
  (code ? BY_CODE.get(code.toUpperCase()) : undefined) ??
  (BY_CODE.get(DEFAULT_COUNTRY_CODE) as Country);

export const DEFAULT_COUNTRY = getCountry(DEFAULT_COUNTRY_CODE);

/**
 * Autocomplete over name, ISO code and dial code — typing "961", "+961", "leb"
 * or "lb" all reach Lebanon.
 *
 * Prefix hits sort above substring hits so the country you spelled out is the
 * first row, not the tenth one that merely contains those letters.
 */
export const searchCountries = (query: string): readonly Country[] => {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) {
    return COUNTRIES;
  }
  const digits = trimmed.replace(/\D/g, '');

  const prefix: Country[] = [];
  const partial: Country[] = [];

  COUNTRIES.forEach(country => {
    const name = country.name.toLowerCase();
    const dial = country.dialCode.slice(1);

    if (
      name.startsWith(trimmed) ||
      country.code.toLowerCase().startsWith(trimmed) ||
      (digits.length > 0 && dial.startsWith(digits))
    ) {
      prefix.push(country);
    } else if (name.includes(trimmed)) {
      partial.push(country);
    }
  });

  return [...prefix, ...partial];
};
