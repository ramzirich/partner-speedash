/**
 * Country calling codes for the phone-number fields.
 *
 * Keyed by ISO 3166-1 alpha-2 because dial codes are **not** unique — +1 covers
 * the whole NANP, +44 covers the UK and the Crown dependencies, +590 covers
 * three French territories. Store the `code`, derive everything else.
 *
 * `flag` is the regional-indicator emoji pair rather than an image asset: no
 * bundle weight, and both iOS and modern Android render them natively.
 */
export interface Country {
  /** ISO 3166-1 alpha-2 — the stable key. */
  code: string;
  name: string;
  /** E.164 country calling code, leading `+` included. */
  dialCode: string;
  nsnLengths: readonly number[];
  /** Regional-indicator emoji pair, e.g. 🇱🇧. */
  flag: string;
}

